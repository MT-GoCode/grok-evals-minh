"""AndroidBench eval: 100 SWE-bench-style Android engineering tasks.

Strategy: vendor + subprocess (mirrors ``matscibench`` pattern).

  * Inference: vendor's ``mini-swe-agent``-based loop runs inside a Docker
    container per task (defined in ``harness/inference/androidbench.py`` and
    ``androidbench_runner.py``). The agent's bash trajectory is driven by
    LiteLLM, so any LiteLLM-supported model name works.
  * Verification: ``harness/evaluation/main.py`` applies the patch and runs
    unit + instrumentation tests in another Docker container, writing a
    ``scores.json`` keyed by ``instance_id`` with a ``Status`` enum value.

For grok-4.3 we don't need a custom backend branch — LiteLLM already maps
``xai/grok-4.3`` to xAI's OpenAI-compatible endpoint and picks up the
``XAI_API_KEY`` environment variable directly.

Key vendor entry points
-----------------------
* CLI (single task):            ``vendor/AndroidBench/cli/run_task.py``
* Agent loop (batch):           ``vendor/AndroidBench/harness/inference/androidbench.py``
* Per-instance agent runner:    ``vendor/AndroidBench/harness/inference/androidbench_runner.py``
* Verifier entry point:         ``vendor/AndroidBench/harness/evaluation/main.py``
* Default prompt + config:      ``vendor/AndroidBench/harness/inference/androidbench.yaml``
* Task definitions:             ``vendor/AndroidBench/dataset/tasks/<instance_id>/task.yaml``

Runtime requirements
--------------------
* Python 3.14 sub-venv at ``vendor/AndroidBench/.venv`` (installed editable).
* Docker daemon accessible from the invoking user (the user must be in the
  ``docker`` group). The agent runs inside ``android-bench-env`` then a
  per-task Docker image is built / pulled (~40 GB each, shared via copy-on-
  write so actual disk pressure is much lower).
* ``XAI_API_KEY`` exported into the subprocess environment.
"""
from __future__ import annotations

import json
import os
import shutil
import subprocess
import time
from pathlib import Path
from typing import Iterable

import yaml

from .._paths import RESULTS_DIR, VENDOR_DIR
from ..base import Eval, EvalMeta, TaskResult
from ..registry import register

# ---------------------------------------------------------------------------
# Paths
# ---------------------------------------------------------------------------

_VENDOR_ROOT = VENDOR_DIR / "AndroidBench"
_VENDOR_PY = _VENDOR_ROOT / ".venv" / "bin" / "python"
_VENDOR_BIN = _VENDOR_ROOT / ".venv" / "bin"
_TASKS_DIR = _VENDOR_ROOT / "dataset" / "tasks"
_OUT_DIR = _VENDOR_ROOT / "out"

# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------


def _check_vendor() -> None:
    """Fail fast with a clear message if the vendor environment is missing."""
    if not _VENDOR_PY.exists():
        raise FileNotFoundError(
            f"Vendor venv python missing at {_VENDOR_PY}. Run:\n"
            f"  uv venv -p 3.14 {_VENDOR_ROOT}/.venv\n"
            f"  uv pip install -e {_VENDOR_ROOT} --python {_VENDOR_PY}"
        )
    if not _TASKS_DIR.is_dir():
        raise FileNotFoundError(
            f"AndroidBench tasks dir missing at {_TASKS_DIR}. "
            "Did you clone github.com/android-bench/android-bench into vendor/AndroidBench?"
        )


def _list_task_ids() -> list[str]:
    """Return all task instance_ids in deterministic alphabetical order.

    AndroidBench ships one directory per task under ``dataset/tasks`` with a
    ``task.yaml`` inside. The summary file ``summary.json`` (generated by
    ``setup_env``) carries metadata, but the per-directory listing is the
    canonical source.
    """
    if not _TASKS_DIR.is_dir():
        return []
    ids: list[str] = []
    for sub in sorted(_TASKS_DIR.iterdir()):
        if not sub.is_dir():
            continue
        if (sub / "task.yaml").exists():
            ids.append(sub.name)
    return ids


def _subprocess_env() -> dict:
    """Environment for the vendor subprocess.

    We rely on LiteLLM's native xAI provider routing — passing
    ``xai/grok-4.3`` as the model name triggers the xAI client, which reads
    ``XAI_API_KEY`` from the env. No need to set ``OPENAI_BASE_URL``.
    """
    env = os.environ.copy()
    # Put the sub-venv's bin first so `agent`, `verifier`, `run_task` resolve
    # to the vendor's entry points (and any pinned tool versions).
    env["PATH"] = f"{_VENDOR_BIN}:{env.get('PATH', '')}"
    # Be defensive: ensure XAI_API_KEY is present.
    if not env.get("XAI_API_KEY"):
        raise RuntimeError(
            "XAI_API_KEY missing from environment. AndroidBench's agent uses "
            "LiteLLM with xai/grok-4.3 which requires XAI_API_KEY."
        )
    return env


def _read_scores_json(run_dir: Path) -> dict:
    """Find and load the scores.json written by the verifier.

    The verifier writes ``<start>_to_<end-1>_scores.json``. For a single-task
    run with ``--task <id>``, it filters but still writes to a file named with
    the initial start/end range; we just glob.
    """
    candidates = sorted(run_dir.glob("*_scores.json"))
    if not candidates:
        raise FileNotFoundError(f"No *_scores.json under {run_dir}")
    # If there are several, prefer the largest end-index range.
    data: dict = {}
    for p in candidates:
        try:
            d = json.loads(p.read_text())
        except json.JSONDecodeError:
            continue
        data.update(d)
    return data


def _status_to_score(status: str) -> float:
    """Map AndroidBench Status enum string to {0.0, 1.0}.

    PASSED / PASSED_FLAKY both count as a pass per the leaderboard convention
    (flaky here means the post-patch tests pass after retries; see
    ``common/models/benchmark.py``).
    """
    if status in {"PASSED", "PASSED_FLAKY"}:
        return 1.0
    return 0.0


# ---------------------------------------------------------------------------
# Eval
# ---------------------------------------------------------------------------


class AndroidBenchEval(Eval):
    meta = EvalMeta(
        name="androidbench",
        area="mobile",
        description=(
            "Google Android Bench: 100 SWE-bench-style Android dev tasks "
            "(Compose migrations, API breaks, networking), Docker-verified "
            "unit/instrumentation tests."
        ),
        paper_url=(
            "https://github.com/android-bench/android-bench/blob/main/docs/tech_report.md"
        ),
        dataset_url="https://github.com/android-bench/android-bench",
        grading=(
            "binary pass/fail per task; tests (unit + instrumentation) executed "
            "inside Docker by vendor harness (PASSED / PASSED_FLAKY -> 1.0, "
            "everything else -> 0.0)."
        ),
        notes=(
            "Grok not on the official leaderboard. Released Mar 6 2026 by Google. "
            "Uses mini-swe-agent + LiteLLM under the hood; we pass "
            "model=xai/grok-4.3 so LiteLLM routes to xAI's chat completions. "
            "Inference and verification both run in Docker containers."
        ),
    )
    model = "grok-4.3"
    # The LiteLLM model id passed to the vendor (their CLI re-strips the
    # provider prefix for filesystem-safe naming).
    litellm_model = "xai/grok-4.3"

    # ---------------- data ----------------

    def ids(self, limit: int | None = None) -> list[str]:
        all_ids = _list_task_ids()
        if limit is not None:
            all_ids = all_ids[:limit]
        return all_ids

    # ---------------- run ----------------

    def _run_one(self, instance_id: str, timeout_s: int = 3600) -> TaskResult:
        """Invoke ``run_task --model xai/grok-4.3 --task <id>`` and parse scores."""
        _check_vendor()

        # Pre-compute the run_name the way run_task.py does so we can locate
        # output reliably. (We pass --run-name is *not* exposed by run_task,
        # so we mirror its scheme: <user>_<ts>_<model>_run_1.)
        user = os.getenv("USER") or "evaluser"
        ts = time.strftime("%Y%m%d_%H%M%S")
        # run_task uses the segment after '/' for the displayed model name.
        model_seg = self.litellm_model.split("/", 1)[-1]
        run_name = f"{user}_{ts}_{model_seg}_run_1"
        run_dir = _OUT_DIR / run_name

        cmd = [
            str(_VENDOR_PY),
            "-m",
            "cli.run_task",
            "--model",
            self.litellm_model,
            "--task",
            instance_id,
        ]

        env = _subprocess_env()
        log_lines: list[str] = []
        t0 = time.perf_counter()
        try:
            proc = subprocess.run(
                cmd,
                cwd=str(_VENDOR_ROOT),
                env=env,
                capture_output=True,
                text=True,
                timeout=timeout_s,
                check=False,
            )
            elapsed = time.perf_counter() - t0
            log_lines.append(f"[run_task] returncode={proc.returncode} elapsed={elapsed:.1f}s")
            stdout_tail = proc.stdout[-2000:] if proc.stdout else ""
            stderr_tail = proc.stderr[-2000:] if proc.stderr else ""
        except subprocess.TimeoutExpired as e:
            elapsed = time.perf_counter() - t0
            return TaskResult(
                task_id=instance_id,
                completion="",
                score=None,
                raw={
                    "error": f"timeout after {timeout_s}s ({elapsed:.1f}s elapsed)",
                    "run_name": run_name,
                    "stdout_tail": (e.stdout or "")[-2000:] if e.stdout else "",
                    "stderr_tail": (e.stderr or "")[-2000:] if e.stderr else "",
                },
            )

        # --- locate scores.json -------------------------------------------
        score_val: float | None = None
        status = ""
        diagnostics = ""
        instance_cost = None
        api_calls = None
        try:
            # The run_task helper sets run_dir as Path("out")/run_name relative
            # to cwd (the vendor root). It may not exist if the agent died
            # before reaching the verifier — try to recover gracefully.
            if not run_dir.is_dir():
                # Look for the most-recent dir mentioning this model.
                candidates = sorted(
                    [p for p in _OUT_DIR.glob(f"*{model_seg}*") if p.is_dir()],
                    key=lambda p: p.stat().st_mtime,
                    reverse=True,
                )
                if candidates:
                    run_dir = candidates[0]
            if run_dir.is_dir():
                scores = _read_scores_json(run_dir)
                rec = scores.get(instance_id) or {}
                status = rec.get("status", "")
                diagnostics = rec.get("diagnostics", "")
                score_val = _status_to_score(status)
                # Pull cost/api stats from the trajectory file if present.
                traj_path = run_dir / "trajectories" / f"{instance_id}.json"
                if traj_path.exists():
                    try:
                        traj = json.loads(traj_path.read_text())
                        ms = traj.get("info", {}).get("extra_info", {}).get("model_stats") or \
                             traj.get("info", {}).get("model_stats") or {}
                        instance_cost = ms.get("instance_cost")
                        api_calls = ms.get("api_calls")
                    except Exception:
                        pass
            else:
                log_lines.append("[parse] run_dir not found, no scores available")
        except Exception as exc:
            log_lines.append(f"[parse error] {type(exc).__name__}: {exc}")

        completion = ""
        patch_path = run_dir / "patches" / f"{instance_id}.patch"
        if patch_path.exists():
            try:
                completion = patch_path.read_text()
            except Exception:
                completion = ""

        return TaskResult(
            task_id=instance_id,
            completion=completion,
            score=score_val,
            raw={
                "run_name": run_dir.name,
                "run_dir": str(run_dir),
                "status": status,
                "diagnostics": diagnostics,
                "elapsed_seconds": elapsed,
                "litellm_model": self.litellm_model,
                "stdout_tail": stdout_tail,
                "stderr_tail": stderr_tail,
                "log": log_lines,
                "instance_cost_usd": instance_cost,
                "api_calls": api_calls,
                "patch_present": patch_path.exists(),
            },
        )

    def run(self, ids: Iterable[str]) -> Iterable[TaskResult]:
        _check_vendor()
        for instance_id in ids:
            yield self._run_one(instance_id)


# Register
register("androidbench", lambda: AndroidBenchEval())
